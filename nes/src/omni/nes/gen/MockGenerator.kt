package omni.nes.gen

/**
 * Deterministic template-based generator: the stand-in for the future LLM.
 * Produces real, validator-GREEN NROM-128 games in the assembler's syntax.
 *
 * Dispatch is keyword-based over [GameSpec.mechanics] (case-insensitive):
 * "dodge"/"dodger"/"meteor"/"collect" -> STAR DODGER (full arcade game:
 * player ship, falling meteors, collectible stars, score, 3 lives, game
 * over, restart — see [DodgerGame]),
 * "score" -> score-counter game, "bounce"/"ball" -> bouncing-ball game,
 * anything with "move"/"dpad"/"sprite" (or nothing recognized) -> D-pad
 * sprite-movement game. Unknown specs can never crash it or produce invalid
 * syntax: the title is sanitized to a single comment line and every template
 * is fixed, reviewed 6502.
 */
class MockGenerator : Generator, ChrProvider {

    /**
     * CHR of the most recently generated game. The dodger template needs
     * its own tiles (ship, meteor, star, letters); everything else uses the
     * shared default set. Set on every [generate] call so [chr] always
     * matches the last assembly produced.
     */
    private var lastChr: ByteArray = ChrData.default()

    override fun chr(): ByteArray = lastChr

    override fun generate(spec: GameSpec): String {
        val mechs = spec.mechanics.joinToString(" ").lowercase()
        val title = sanitizeTitle(spec.title)
        return when {
            "dodge" in mechs || "dodger" in mechs || "meteor" in mechs || "collect" in mechs -> {
                lastChr = DodgerChr.data()
                DodgerGenerator().generate(spec)
            }
            "score" in mechs -> {
                lastChr = ChrData.default()
                scoreGame(title, spec)
            }
            "bounce" in mechs || "ball" in mechs -> {
                lastChr = ChrData.default()
                bounceGame(title, spec)
            }
            else -> {
                lastChr = ChrData.default()
                dpadGame(title, spec)
            }
        }
    }

    // ------------------------------------------------------------------
    // spec hygiene: the title lands in a `;` comment, so it must be one
    // line of comment-safe text. This is the spec-injection guard.
    // ------------------------------------------------------------------
    internal fun sanitizeTitle(title: String): String {
        val oneLine = title.replace(Regex("\\s+"), " ").trim()
        val safe = oneLine.replace(Regex("[^A-Za-z0-9 _.,!?'()+-]"), "_")
        return safe.take(80).ifEmpty { "UNTITLED" }
    }

    /** Spec text goes into `;` comments only. Newlines would break out of the
     *  comment and let a hostile spec inject real labels/opcodes, so every
     *  spec field is flattened to one line and stripped of anything outside a
     *  conservative printable set. */
    internal fun sanitizeComment(s: String): String =
        s.replace('\n', ' ').replace('\r', ' ')
            .map { c -> if (c.code in 32..126 && c != ';') c else '_' }
            .joinToString("").take(200)

    // ------------------------------------------------------------------
    // shared NROM-128 scaffold
    // ------------------------------------------------------------------
    internal fun scaffold(
        title: String,
        spec: GameSpec,
        zpDecls: String,
        initCode: String,
        nmiCode: String,
        /** Subroutines (JSR targets): emitted after the NMI/IRQ handlers so
         *  the handler never falls through into them. */
        tailCode: String = "",
    ): String = buildString {
        appendLine("; ${sanitizeComment(title)} - generated by OMNI MockGenerator (deterministic template)")
        appendLine("; genre: ${sanitizeComment(spec.genre)} | controls: ${sanitizeComment(spec.controls)}")
        appendLine("; mechanics: ${spec.mechanics.joinToString(", ") { sanitizeComment(it) }}")
        appendLine("; NROM-128. Sprite 0 lives in the OAM shadow at $$0200.")
        appendLine()
        appendLine("; ---- zero page ----")
        append(zpDecls)
        appendLine("padstate = \$10")
        appendLine("padprev  = \$11")
        appendLine("padtmp   = \$12")
        appendLine()
        appendLine(".org \$C000")
        appendLine()
        appendLine("RESET:")
        appendLine("    SEI")
        appendLine("    CLD")
        appendLine("    LDX #\$40")
        appendLine("    STX \$4017           ; disable APU frame IRQ")
        appendLine("    LDX #\$00")
        appendLine("    STX \$4010           ; disable DMC IRQs")
        appendLine("    STX \$2000           ; NMI off")
        appendLine("    STX \$2001           ; rendering off")
        appendLine("    STX \$4015           ; APU channels off")
        appendLine("    DEX")
        appendLine("    TXS                 ; SP = \$FF")
        appendLine("    INX                 ; X = 0")
        appendLine()
        appendLine("vblank1:")
        appendLine("    BIT \$2002")
        appendLine("    BPL vblank1         ; PPU warm-up")
        appendLine()
        appendLine("    TXA                 ; A = 0")
        appendLine("clear:")
        appendLine("    STA \$0000,X")
        appendLine("    STA \$0100,X")
        appendLine("    STA \$0200,X")
        appendLine("    STA \$0300,X")
        appendLine("    STA \$0400,X")
        appendLine("    STA \$0500,X")
        appendLine("    STA \$0600,X")
        appendLine("    STA \$0700,X")
        appendLine("    INX")
        appendLine("    BNE clear")
        appendLine()
        appendLine("vblank2:")
        appendLine("    BIT \$2002")
        appendLine("    BPL vblank2")
        appendLine()
        appendLine("    ; palette upload during forced blank (rendering off: legal)")
        appendLine("    LDA #\$3F")
        appendLine("    STA \$2006")
        appendLine("    LDA #\$00")
        appendLine("    STA \$2006")
        appendLine("    LDX #\$00")
        appendLine("pal_loop:")
        appendLine("    LDA palette,X")
        appendLine("    STA \$2007")
        appendLine("    INX")
        appendLine("    CPX #\$20")
        appendLine("    BNE pal_loop")
        appendLine()
        append(initCode)
        appendLine("    CLI")
        appendLine("    LDA #%10000000")
        appendLine("    STA \$2000           ; NMI on")
        appendLine("    LDA #%00011110")
        appendLine("    STA \$2001           ; rendering on: bg + sprites")
        appendLine("main:")
        appendLine("    JMP main            ; idle; NMI does the work")
        appendLine()
        appendLine("NMI:")
        appendLine("    PHA")
        appendLine("    TXA")
        appendLine("    PHA")
        appendLine("    TYA")
        appendLine("    PHA")
        append(nmiCode)
        appendLine("    LDA #\$02")
        appendLine("    STA \$4014           ; OAM DMA from \$0200")
        appendLine("    PLA")
        appendLine("    TAY")
        appendLine("    PLA")
        appendLine("    TAX")
        appendLine("    PLA")
        appendLine("    RTI")
        appendLine()
        appendLine("IRQ:")
        appendLine("    RTI")
        appendLine()
        appendLine("; controller 1 -> padstate. Bits: 7=A 6=B 5=Select 4=Start 3=Up 2=Down 1=Left 0=Right")
        appendLine("read_pad:")
        appendLine("    LDA #\$01")
        appendLine("    STA \$4016")
        appendLine("    LDA #\$00")
        appendLine("    STA \$4016           ; strobe")
        appendLine("    LDX #\$08")
        appendLine("rp_loop:")
        appendLine("    LDA \$4016")
        appendLine("    LSR A               ; bit 0 -> carry")
        appendLine("    ROL padstate")
        appendLine("    DEX")
        appendLine("    BNE rp_loop")
        appendLine("    RTS")
        appendLine()
        if (tailCode.isNotEmpty()) {
            appendLine("; ---- subroutines ----")
            append(tailCode)
            appendLine()
        }
        appendLine("palette:")
        appendLine("    .byte \$0F,\$0F,\$0F,\$0F, \$0F,\$16,\$26,\$36, \$0F,\$0F,\$0F,\$0F, \$0F,\$0F,\$0F,\$0F")
        appendLine("    .byte \$0F,\$0F,\$0F,\$0F, \$0F,\$16,\$26,\$36, \$0F,\$0F,\$0F,\$0F, \$0F,\$0F,\$0F,\$0F")
        appendLine()
        appendLine("    .org \$FFFA")
        appendLine("    .word NMI, RESET, IRQ")
    }

    /** D-pad movement shared by the dpad and score games (sprite 0 at $0200). */
    private fun dpadMoveCode() = """
    JSR read_pad
    LDA padstate
    AND #$08            ; Up
    BEQ no_up
    LDA $0200
    SEC
    SBC #$01
    CMP #$10
    BCC no_up           ; clamp top
    STA $0200
no_up:
    LDA padstate
    AND #$04            ; Down
    BEQ no_down
    LDA $0200
    CLC
    ADC #$01
    CMP #${'$'}E8
    BCS no_down         ; clamp bottom
    STA $0200
no_down:
    LDA padstate
    AND #$02            ; Left
    BEQ no_left
    LDA $0203
    SEC
    SBC #$01
    CMP #$08
    BCC no_left         ; clamp left
    STA $0203
no_left:
    LDA padstate
    AND #$01            ; Right
    BEQ no_right
    LDA $0203
    CLC
    ADC #$01
    CMP #${'$'}F8
    BCS no_right        ; clamp right
    STA $0203
no_right:
""".trimIndent().lines().joinToString("\n") { "    $it" } + "\n"

    // ------------------------------------------------------------------
    // game (a): D-pad sprite movement
    // ------------------------------------------------------------------
    internal fun dpadGame(title: String, spec: GameSpec): String {
        val init = """
    ; sprite 0: player block at (120,120)
    LDA #$78
    STA $0200           ; Y
    LDA #$01
    STA $0201           ; tile 1 (player)
    LDA #$00
    STA $0202           ; attributes
    LDA #$78
    STA $0203           ; X
""".trimIndent().lines().joinToString("\n") { "    $it" } + "\n"
        val nmi = dpadMoveCode() + """
    ; A cycles tile, B cycles attributes
    LDA padstate
    AND #$80
    BEQ no_a
    LDA padprev
    AND #$80
    BNE no_a
    INC $0201
    LDA $0201
    CMP #$04
    BCC a_done
    LDA #$01
    STA $0201
a_done:
no_a:
    LDA padstate
    AND #$40
    BEQ no_b
    LDA padprev
    AND #$40
    BNE no_b
    INC $0202
no_b:
    LDA padstate
    STA padprev
""".trimIndent().lines().joinToString("\n") { "    $it" } + "\n"
        return scaffold(title, spec, "", init, nmi)
    }

    // ------------------------------------------------------------------
    // game (b): score counter (D-pad moves, A scores, digits on screen)
    // ------------------------------------------------------------------
    internal fun scoreGame(title: String, spec: GameSpec): String {
        val zp = "score0 = \$00\nscore1 = \$01\nscore2 = \$02\nscore3 = \$03\nframectr = \$04\n"
        val initSimple = """
    ; sprite 0: player block at (120,120)
    LDA #$78
    STA $0200
    LDA #$01
    STA $0201
    LDA #$00
    STA $0202
    LDA #$78
    STA $0203
    ; sprites 1-4: score digits at Y=116, X=112..136
    LDA #$74
    STA $0204
    STA $0208
    STA $020C
    STA $0210
    LDA #$10
    STA $0205
    STA $0209
    STA $020D
    STA $0211
    LDA #$00
    STA $0206
    STA $020A
    STA $020E
    STA $0212
    LDA #$70
    STA $0207
    LDA #$78
    STA $020B
    LDA #$80
    STA $020F
    LDA #$88
    STA $0213
""".trimIndent().lines().joinToString("\n") { "    $it" } + "\n"
        val nmi = dpadMoveCode() + """
    ; A scores (edge-triggered)
    LDA padstate
    AND #$80
    STA padtmp
    BEQ a_skip
    LDA padprev
    AND #$80
    BNE a_skip
    JSR inc_score
a_skip:
    LDA padtmp
    STA padprev
    ; auto-tick: +1 every 30 frames
    INC framectr
    LDA framectr
    CMP #$1E
    BCC tick_done
    LDA #$00
    STA framectr
    JSR inc_score
tick_done:
    ; digits -> tiles (sprite i tile = 16 + digit)
    LDX #$00
    LDY #$00
upd_loop:
    LDA score0,X
    CLC
    ADC #$10
    STA $0205,Y
    INX
    INY
    INY
    INY
    INY
    CPX #$04
    BCC upd_loop
""".trimIndent().lines().joinToString("\n") { "    $it" } + "\n"
        val tail = """
; +1 to the 4-digit score with decimal carry
inc_score:
    LDX #$00
isc_loop:
    INC score0,X
    LDA score0,X
    CMP #$0A
    BCC isc_done
    LDA #$00
    STA score0,X
    INX
    CPX #$04
    BCC isc_loop
isc_done:
    RTS
""".trimIndent().lines().joinToString("\n") { "    $it" } + "\n"
        return scaffold(title, spec, zp, initSimple, nmi, tail)
    }

    // ------------------------------------------------------------------
    // game (c): bouncing ball (A toggles 1x/2x speed)
    // ------------------------------------------------------------------
    internal fun bounceGame(title: String, spec: GameSpec): String {
        val zp = "ballx = \$00\nbally = \$01\ndx = \$02\ndy = \$03\nspeed = \$04\n"
        val init = """
    LDA #$78
    STA ballx
    LDA #$6E
    STA bally
    LDA #$01
    STA dx
    STA dy
    STA speed
    ; sprite 0: ball
    LDA bally
    STA $0200
    LDA #$02
    STA $0201           ; tile 2 (ball)
    LDA #$00
    STA $0202
    LDA ballx
    STA $0203
""".trimIndent().lines().joinToString("\n") { "    $it" } + "\n"
        val nmi = """
    JSR read_pad
    ; A toggles speed 1x/2x (edge-triggered)
    LDA padstate
    AND #$80
    BEQ sp_rel
    LDA padprev
    BNE sp_done
    LDA speed
    EOR #$03            ; 1 <-> 2
    STA speed
    LDA #$80
    STA padprev
    JMP sp_done
sp_rel:
    LDA #$00
    STA padprev
sp_done:
    JSR move_ball
    LDA speed
    CMP #$02
    BNE spd_done
    JSR move_ball       ; 2x speed: integrate twice
spd_done:
    LDA bally
    STA $0200
    LDA ballx
    STA $0203
""".trimIndent().lines().joinToString("\n") { "    $it" } + "\n"
        val tail = """
; integrate position, bouncing off the walls (X: 0..239, Y: 16..223)
move_ball:
    LDA ballx
    CLC
    ADC dx
    STA ballx
    LDX dx
    CPX #$01
    BEQ mx_right
    CMP #${'$'}FF            ; wrapped below 0?
    BNE mx_done
    LDA #$01
    STA dx
    LDA #$00
    STA ballx
    JMP mx_done
mx_right:
    BCS mx_hit_r        ; wrapped past 255
    CMP #${'$'}F0
    BCC mx_done
mx_hit_r:
    LDA #${'$'}FF
    STA dx
    LDA #${'$'}EF
    STA ballx
mx_done:
    LDA bally
    CLC
    ADC dy
    STA bally
    LDX dy
    CPX #$01
    BEQ my_down
    CMP #${'$'}FF
    BNE my_done
    LDA #$01
    STA dy
    LDA #$10
    STA bally
    JMP my_done
my_down:
    BCS my_hit_b
    CMP #${'$'}E0
    BCC my_done
my_hit_b:
    LDA #${'$'}FF
    STA dy
    LDA #${'$'}DF
    STA bally
my_done:
    RTS
""".trimIndent().lines().joinToString("\n") { "    $it" } + "\n"
        return scaffold(title, spec, zp, init, nmi, tail)
    }
}
